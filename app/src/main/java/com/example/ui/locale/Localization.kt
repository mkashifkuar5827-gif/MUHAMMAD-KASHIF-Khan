    fun get(key: String, lang: AppLanguage): String {
        return when (lang) {
            AppLanguage.URDU -> ur[key] ?: en[key] ?: key
            AppLanguage.ARABIC -> ar[key] ?: en[key] ?: key
            AppLanguage.ENGLISH -> en[key] ?: key
        }
    }
